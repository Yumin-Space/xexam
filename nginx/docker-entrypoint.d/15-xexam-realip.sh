#!/bin/sh
# Renders /tmp/xexam-realip.conf (included in http {} by nginx.conf) from the environment:
#   XEXAM_TRUSTED_PROXIES  addresses or CIDRs, separated by commas and / or spaces; the peers whose forwarded client
#                          address and location headers are believed. Empty = trust nobody.
#   XEXAM_REAL_IP_HEADER   CF-Connecting-IP (default) | X-Forwarded-For | X-Real-IP
# Anything invalid: a warning on stderr and a file that trusts nobody (fail closed).
set -eu

OUT=/tmp/xexam-realip.conf
HEADER="${XEXAM_REAL_IP_HEADER:-CF-Connecting-IP}"
LIST="${XEXAM_TRUSTED_PROXIES:-}"

fail_closed() {
    echo "xexam-realip: $1; trusting no proxy" >&2
    cat > "$OUT" <<CONF
# generated by 15-xexam-realip.sh: no trusted proxy
geo \$realip_remote_addr \$xexam_trusted {
    default 0;
}
CONF
    exit 0
}

# One token: an IPv4 address (octets 0-255) or an IPv6 address, optionally with a prefix length; never a prefix of 0.
valid_token() {
    t="$1"
    printf '%s' "$t" | grep -Eq '^[0-9A-Fa-f:.]+(/[0-9]{1,3})?$' || return 1
    addr="${t%%/*}"
    case "$t" in
        */*) prefix="${t#*/}" ;;
        *) prefix="" ;;
    esac
    if [ -n "$prefix" ]; then
        [ "$prefix" -ge 1 ] || return 1
    fi
    case "$addr" in
        *:*)
            printf '%s' "$addr" | grep -Eq '^[0-9A-Fa-f:.]+$' || return 1
            [ -z "$prefix" ] || [ "$prefix" -le 128 ] || return 1
            ;;
        *)
            printf '%s' "$addr" | grep -Eq '^[0-9]{1,3}(\.[0-9]{1,3}){3}$' || return 1
            [ -z "$prefix" ] || [ "$prefix" -le 32 ] || return 1
            oldifs="$IFS"; IFS=.
            for o in $addr; do
                [ "$o" -le 255 ] || { IFS="$oldifs"; return 1; }
            done
            IFS="$oldifs"
            ;;
    esac
    return 0
}

case "$HEADER" in
    CF-Connecting-IP|X-Forwarded-For|X-Real-IP) ;;
    *) fail_closed "XEXAM_REAL_IP_HEADER must be CF-Connecting-IP, X-Forwarded-For or X-Real-IP" ;;
esac

TOKENS=$(printf '%s' "$LIST" | tr ',' ' ')
for t in $TOKENS; do
    valid_token "$t" || fail_closed "XEXAM_TRUSTED_PROXIES has an invalid entry (a refused or malformed address or CIDR)"
done

{
    echo "# generated by 15-xexam-realip.sh"
    for t in $TOKENS; do
        echo "set_real_ip_from $t;"
    done
    echo "real_ip_header $HEADER;"
    if [ "$HEADER" = "X-Forwarded-For" ]; then
        echo "real_ip_recursive on;"
    fi
    echo 'geo $realip_remote_addr $xexam_trusted {'
    echo "    default 0;"
    for t in $TOKENS; do
        echo "    $t 1;"
    done
    echo "}"
} > "$OUT"
